import { join } from "node:path";
import {
  anthropicBase,
  assertModels,
  assertProtocol,
  childDir,
  ensurePrivateDir,
  modelChoices,
  openAiBase,
  requireLimits,
  writePrivateFile,
  type AdapterConnection,
  type AdapterModel,
  type BuiltProvider,
} from "./adapter-common";

const PROVIDER = "ppm";

function apiFor(protocol: AdapterConnection["protocol"]): string {
  if (protocol === "chat") return "openai-completions";
  if (protocol === "responses") return "openai-responses";
  return "anthropic-messages";
}

/** The provider entry, in the same shape as a models.json provider. No key. */
function providerConfig(connection: AdapterConnection, models: readonly AdapterModel[]) {
  return {
    name: connection.name || "PPM gateway",
    baseUrl: connection.protocol === "anthropic" ? anthropicBase(connection.url) : openAiBase(connection.url),
    api: apiFor(connection.protocol),
    models: models.map((model) => ({
      id: model.id,
      name: model.label.trim() || model.id,
      reasoning: model.caps?.reasoning ?? false,
      input: model.caps?.image ? ["text", "image"] : ["text"],
      cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
      contextWindow: model.context,
      maxTokens: model.output,
    })),
  };
}

/**
 * A Pi extension that registers the gateway as provider "ppm". The key is read
 * from PPM_GATEWAY_KEY at runtime, so the file holds no secret (OMP does not
 * expand "$VAR" in models.json, but an extension reads process.env directly).
 */
function extensionSource(connection: AdapterConnection, models: readonly AdapterModel[]): string {
  return `// Generated by Providers Manager. Registers the gateway "${connection.name.replace(/[\r\n]/g, " ")}".
const CONFIG = ${JSON.stringify(providerConfig(connection, models), null, 2)};
export default function (pi) {
  pi.registerProvider(${JSON.stringify(PROVIDER)}, { ...CONFIG, apiKey: process.env.PPM_GATEWAY_KEY || "ppm-no-key" });
}
`;
}

/**
 * Pi and OMP load the gateway from a generated extension passed with `-e`
 * (Paseo launches the provider command, then adds --mode rpc --model …). The
 * agent directory stays the user's real one: settings, MCP servers, AGENTS.md,
 * skills, extensions and sessions are shared with their own Pi/OMP. Earlier
 * versions used a private agent directory per generation, which hid all of
 * that and lost history on every change.
 */
async function writeExtension(
  agent: "pi" | "omp",
  connection: AdapterConnection,
  models: readonly AdapterModel[],
  dir: string,
): Promise<string> {
  const path = join(await ensurePrivateDir(childDir(dir, agent)), "ppm-extension.mjs");
  await writePrivateFile(path, extensionSource(connection, models));
  return path;
}

export async function piProvider(
  connection: AdapterConnection,
  models: readonly AdapterModel[],
  dir: string,
): Promise<BuiltProvider> {
  assertProtocol("Pi", connection.protocol, ["chat", "responses", "anthropic"]);
  assertModels(models);
  const limited = requireLimits("Pi", models);
  const extension = await writeExtension("pi", connection, limited, dir);
  return {
    extends: "pi",
    command: ["pi", "-e", extension],
    env: {
      PI_SKIP_VERSION_CHECK: "1",
      // Always present so a removed key cannot survive a provider-env merge.
      // The dummy keeps Pi from falling back to an unrelated ambient credential
      // when the gateway genuinely needs no auth.
      PPM_GATEWAY_KEY: connection.key || "ppm-no-key",
    },
    models: modelChoices("pi", models),
  };
}

export async function ompProvider(
  connection: AdapterConnection,
  models: readonly AdapterModel[],
  dir: string,
): Promise<BuiltProvider> {
  assertProtocol("Oh My Pi", connection.protocol, ["chat", "responses", "anthropic"]);
  assertModels(models);
  const limited = requireLimits("Oh My Pi", models);
  const extension = await writeExtension("omp", connection, limited, dir);
  return {
    extends: "omp",
    command: ["omp", "-e", extension],
    env: {
      PPM_GATEWAY_KEY: connection.key || "ppm-no-key",
    },
    models: modelChoices("omp", models),
  };
}
